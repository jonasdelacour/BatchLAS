// Backend-deducing overload `NAME(ctx, args...)` of `NAME<Backend, T, ...>(ctx, ...)`.
// The pack is forwarded, not restated, so the primary's defaults still apply. The
// requires-clause must stay: unconstrained, this beats option-struct overloads and
// fails inside its body. Even constrained, it beats `const MA&` for prvalues, so
// checks must also live on the <Backend> option overloads.
// evidence: docs/design/api-conventions.md#api-conventions-the-variadic-dispatch-overload-and-its-requires-clause
#define BATCHLAS_DISPATCH_ON_QUEUE(NAME)                                        \
    template <typename... Args>                                                 \
        requires requires(Queue& probe_ctx, Args&&... probe_args) {             \
            NAME<::batchlas::detail::kProbeBackend>(probe_ctx,                  \
                                                    std::forward<Args>(probe_args)...); \
        }                                                                       \
    inline auto NAME(Queue& ctx, Args&&... args) {                              \
        ::batchlas::detail::require_pack_accessible(ctx, #NAME, args...);       \
        return ::batchlas::detail::with_backend_gated<                          \
            ::batchlas::detail::needs_fp64_v<Args...>>(ctx, #NAME, [&](auto Back) { \
            return NAME<Back.value>(ctx, std::forward<Args>(args)...);          \
        });                                                                     \
    }
