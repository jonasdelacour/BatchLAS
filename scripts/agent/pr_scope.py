"""What this branch adds against origin/main, as the reviewer will see it. Run before every push
and show the REVIEW lines to the user; never push past one silently.

    python3 scripts/agent/pr_scope.py [--base origin/main] [--max-kb 500]

Flags what has drawn objections: large or binary files, raw campaign data under
benchmarks/results/, new files outside the usual trees, new headers, loosened test tolerances,
ledger lines removed, tuned tables edited without a ledger change (they are generated by
scripts/sweep_to_table.py), and kernel-hash pins changed by hand. Exit 0 clean, 1 when any REVIEW
line was printed.
"""

import argparse
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
USUAL = ("src/", "include/", "tests/", "docs/", "tools/", "scripts/", "benchmarks/", "cmake/",
         ".github/", "tuned/", "python/", "examples/", ".claude/")
# Generated or append-only by design: the tuning ledgers and the tables built from them.
EXPECTED_DATA = ("benchmarks/results/tuning/ledger/", "tuned/")
TOLERANCE = re.compile(r"\b(tol|tolerance|eps|slack|rtol|atol|EXPECT_VERIFY|EXPECT_NEAR|ASSERT_NEAR)\b",
                       re.I)


def git(*args):
    return subprocess.run(["git", "-C", REPO] + list(args), capture_output=True, text=True,
                          check=True).stdout


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--base", default="origin/main")
    ap.add_argument("--max-kb", type=int, default=500)
    args = ap.parse_args()
    base = git("merge-base", args.base, "HEAD").strip()
    rng = [base]  # against the working tree, so uncommitted edits are reviewed too
    status = [l.split("\t") for l in git("diff", "--name-status", "-M", *rng).splitlines() if l]
    status += [["A", p] for p in git("ls-files", "--others", "--exclude-standard").splitlines()]
    numstat = {}
    for l in git("diff", "--numstat", "-M", *rng).splitlines():
        a, d, p = l.split("\t", 2)
        numstat[p.split(" => ")[-1].rstrip("}")] = (a, d)
    adds = sum(int(a) for a, _ in numstat.values() if a != "-")
    dels = sum(int(d) for _, d in numstat.values() if d != "-")
    print("scope vs %s (merge-base %s): %d file(s), +%d/-%d lines"
          % (args.base, base[:10], len(status), adds, dels))
    review = []
    raw_dirs, headers = {}, []

    for row in status:
        kind, path = row[0][0], row[-1]
        full = os.path.join(REPO, path)
        size = os.path.getsize(full) if os.path.isfile(full) else 0
        a, _ = numstat.get(path, ("", ""))
        if kind != "D" and size > args.max_kb * 1024 and not path.startswith(EXPECTED_DATA):
            review.append("large file (%d KB): %s" % (size // 1024, path))
        if kind != "D" and a == "-":
            review.append("binary file: %s" % path)
        if path.startswith("benchmarks/results/") and kind != "D" and not path.startswith(EXPECTED_DATA):
            d = "/".join(path.split("/")[:3])
            n, kb = raw_dirs.get(d, (0, 0))
            raw_dirs[d] = (n + 1, kb + size // 1024)
        if kind == "A" and not path.startswith(USUAL) and "/" in path:
            review.append("new file outside the usual trees: %s" % path)
        if kind == "A" and "/" not in path:
            review.append("new file at the repository root: %s" % path)
        if kind == "A" and path.endswith((".hh", ".h", ".hpp")):
            headers.append(path)

    for d, (n, kb) in sorted(raw_dirs.items()):
        review.append("results data: %d file(s), %d KB under %s (ask before committing campaign "
                      "dumps; distil into docs/perf)" % (n, kb, d))
    if headers:
        review.append("%d new header(s) (does an existing class cover each?): %s"
                      % (len(headers), " ".join(headers)))

    diff = git("diff", "-U0", *rng, "--", "tests/")
    current, removed, added = "", [], set()
    for line in diff.splitlines():
        if line.startswith("+++ "):
            current = line[6:]
        elif line.startswith(("-", "+")) and not line.startswith(("---", "+++")):
            body = line[1:].strip()
            if current.startswith("tests/known-failures") and line.startswith("-") and body \
                    and not body.startswith("#"):
                review.append("ledger entry removed (say why in the PR): %s: %s" % (current, body))
            elif current.startswith("tests/known-failures") and line.startswith("+") and body \
                    and not body.startswith("#"):
                review.append("ledger entry ADDED (a new accepted failure needs the user's OK): %s: %s"
                              % (current, body))
            elif line.startswith("+"):
                added.add(body)
            elif current.endswith((".cc", ".hh")) and current != "tests/tune_tests.cc" \
                    and TOLERANCE.search(body) \
                    and not body.startswith(("//", "<<")) and re.search(r"\d|Slack", body):
                removed.append((current, body))
    # A moved line is not a changed bound; only report text that did not come back verbatim.
    changed_bounds = [(f, b) for f, b in removed if b not in added]
    for f, b in changed_bounds[:8]:
        review.append("tolerance/verify line changed (loosened?): %s: %s" % (f, b[:120]))
    if len(changed_bounds) > 8:
        review.append("... and %d more tolerance/verify line(s) in tests/" % (len(changed_bounds) - 8))

    changed = {row[-1] for row in status}
    tables = sorted(p for p in changed if p.startswith("tuned/") and p.endswith(".txt"))
    ledgers = [p for p in changed if p.startswith("benchmarks/results/") or "ledger" in p]
    if tables and not ledgers:
        review.append("tuned tables changed with no ledger change (hand edit? regenerate with "
                      "scripts/sweep_to_table.py): %s" % " ".join(tables))
    if "tests/tune_tests.cc" in changed and re.search(r'^[-+].*\{"\w+", "[0-9a-f]{8}"\}',
                                                     git("diff", *rng, "--", "tests/tune_tests.cc"), re.M):
        review.append("kernel-hash pins changed: regenerate with scripts/agent/repin_tune_hashes.py, "
                      "do not hand-merge")

    for r in review:
        print("REVIEW  " + r)
    if not review:
        print("nothing to flag")
    return 1 if review else 0


if __name__ == "__main__":
    sys.exit(main())
