#!/usr/bin/env python3
"""Generate src/routing/generated/potrf_rules.inc from routing/rules/*/potrf.rules.

    python3 evaluation/routing/gen_rules_header.py [--check]

--check regenerates in memory and fails if the committed .inc differs (a ctest). The arch
index maps each routing profile to its model RuleSet when the profile's gate passed and a
rules file exists, and to the hand RuleSet otherwise.
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RULES = os.path.join(REPO, "routing", "rules")
OUT = os.path.join(REPO, "src", "routing", "generated", "potrf_rules.inc")
DTYPES = ("float", "double", "cfloat", "cdouble")
UPLOS = ("L", "U")
PROFILES = ("sm_89", "sm_120")   # arch::RoutingProfile, Unset excluded
LINE = re.compile(r"^R(\d+) (\w+) ([LU]) n \[(\d+),(\w+)\] batch \[(\d+),(\w+)\] -> (.+?) ; src=(\w+)$")
SRC = {"hand": "Hand", "model": "Model", "measured": "Measured", "override": "Override"}


def parse(path, names):
    rules, meta = [], {}
    for raw in open(path):
        line = raw.rstrip("\n")
        if line.startswith("#"):
            for tok in line[1:].split():
                if "=" in tok:
                    k, v = tok.split("=", 1)
                    meta.setdefault(k, v)
            continue
        if not line.strip():
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"gen_rules_header: {path}: cannot parse: {line}")
        rid, d, u, n0, n1, b0, b1, rank, src = m.groups()
        tiers = [t.strip() for t in rank.split(">")]
        for t in tiers:
            if t not in names:
                names.append(t)
        rules.append({"id": int(rid), "key": DTYPES.index(d) * 2 + UPLOS.index(u),
                      "lo": (int(n0), int(b0)), "hi": (n1, b1), "rank": tiers, "src": src})
    rules.sort(key=lambda r: (r["key"], r["id"]))
    return rules, meta


def lim(v):
    return "kInf" if v == "inf" else str(int(v))


def emit_set(o, tag, rules, meta, names):
    o.append(f"inline constexpr Rule k_{tag}_rules[] = {{")
    for r in rules:
        rank = ", ".join(f"Candidate{{{names.index(t)}, {{}}}}" for t in r["rank"])
        o.append(f"    {{{r['id']}u, {r['key']}, {{{r['lo'][0]}, {r['lo'][1]}, 0, 0}}, "
                 f"{{{lim(r['hi'][0])}, {lim(r['hi'][1])}, 0, 0}}, {{{rank}}}, {len(r['rank'])}, "
                 f"Source::{SRC[r['src']]}}},")
    o.append("};")
    off = [0] * 9
    for r in rules:
        off[r["key"] + 1] += 1
    for k in range(8):
        off[k + 1] += off[k]
    o.append(f"inline constexpr std::uint32_t k_{tag}_off[] = {{{', '.join(map(str, off))}}};")
    prov = meta.get("provenance", "").replace('"', "'")
    cf = [meta.get(k, "0") for k in ("cus", "local_mem", "max_wg", "sg")]
    o.append(f"inline constexpr RuleSet k_{tag}{{\"potrf\", \"{meta.get('arch', tag)}\", \"{prov}\",")
    o.append(f"    k_{tag}_rules, k_{tag}_rules + {len(rules)}, k_{tag}_off, 8, "
             f"{{{', '.join(cf)}}}}};")


def generate():
    names = list(json.load(open(os.path.join(REPO, "routing", "candidacy.json")))["potrf"]["tiers"])
    sets = {}
    for arch in sorted(os.listdir(RULES)):
        p = os.path.join(RULES, arch, "potrf.rules")
        if os.path.exists(p):
            sets[arch] = parse(p, names)
    if "hand" not in sets:
        sys.exit("gen_rules_header: routing/rules/hand/potrf.rules is required")
    o = ["// GENERATED by evaluation/routing/gen_rules_header.py from routing/rules/*/potrf.rules",
         "// -- do not edit; regenerate. tests/CMakeLists.txt checks it (--check).",
         "#pragma once",
         "",
         "namespace batchlas::routing::potrf_rules {",
         "",
         f"inline constexpr std::array<std::string_view, {len(names)}> kNames{{"
         + ", ".join(f'"{n}"' for n in names) + "};",
         ""]
    for arch, (rules, meta) in sets.items():
        emit_set(o, arch, rules, meta, names)
        o.append("")
    o.append("// The ONE arch index: a profile whose gate passed and that has a model rules file")
    o.append("// gets it; every other profile, and Unset, gets the hand transcription.")
    o.append("inline const RuleSet& rules_for_profile(arch::RoutingProfile p) {")
    o.append("    switch (p) {")
    for prof in PROFILES:
        pj = json.load(open(os.path.join(HERE, "profiles", prof + ".json")))
        use = prof if (pj["gate"]["verdict"] == "PASS" and prof in sets) else "hand"
        o.append(f"        case arch::RoutingProfile::{prof}: return k_{use};   "
                 f"// gate {pj['gate']['verdict']}")
    o.append("        default: return k_hand;")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("}  // namespace batchlas::routing::potrf_rules")
    return "\n".join(o) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit(f"gen_rules_header: {os.path.relpath(OUT, REPO)} is stale; regenerate it")
        print("potrf_rules.inc is current")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    main()
