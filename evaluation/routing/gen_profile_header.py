#!/usr/bin/env python3
"""Generate src/backends/potrf_profile_constants.hh from evaluation/routing/profiles/*.json.

    python3 evaluation/routing/gen_profile_header.py            # write the header
    python3 evaluation/routing/gen_profile_header.py --check    # exit 1 if it is stale

The header is COMMITTED; tests/CMakeLists.txt runs --check as a ctest so it cannot drift from
the committed profile JSON. Everything routing needs comes from the profile JSON: constants and
measured support boxes per (route, dtype, uplo), the gate verdict (model_enabled), the margin,
and the device facts the plan reads beyond what the device reports (thread/group caps,
per-kernel registers).
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "src", "backends", "potrf_profile_constants.hh")
PROFILES = ("sm_89", "sm_120")   # arch::RoutingProfile order, Unset excluded
ROUTES = ("native:tiny", "native:cta", "native:lpanel", "native:blocked", "vendor")  # kPotrfOrder
DTYPES = ("float", "double", "cfloat", "cdouble")
PARAMS = ("t_launch", "s_per_flop", "s_per_byte", "t_step", "s_per_slot", "t_item")
REG_KEYS = (("t8", "tiny[0]"), ("t16", "tiny[1]"), ("t32", "tiny[2]"), ("cta_sg", "cta_sg"),
            ("cta_wg", "cta_wg"), ("lp", "lpanel"), ("lp16", "lpanel_nb16"))


def num(x):
    return repr(float(x))


def entry(e):
    if e is None:
        return "{}"
    c = ", ".join(num(e["constants"].get(k, 0.0)) for k in PARAMS)
    s = e.get("support")
    box = (f"{{{s['n_min']}, {s['n_max']}, {s['batch_min']}, {s['batch_max']}, {s['rows']}}}"
           if s else "{}")
    return f"{{true, {{{c}}}, {box}}}"


def regs(r):
    parts = []
    tiny = [str(r.get(k, 0)) for k in ("t8", "t16", "t32")]
    parts.append("{" + ", ".join(tiny) + "}")
    for k in ("cta_sg", "cta_wg", "lp", "lp16"):
        parts.append(str(r.get(k, 0)))
    return "{" + ", ".join(parts) + "}"


def render(profiles):
    L = []
    L.append("#pragma once")
    L.append("")
    L.append("// GENERATED by evaluation/routing/gen_profile_header.py from")
    L.append("// evaluation/routing/profiles/{" + ",".join(PROFILES) + "}.json -- do not edit; regenerate.")
    L.append("// tests/CMakeLists.txt checks it against the committed JSON. SYCL-free.")
    L.append("// evidence: docs/perf/potrf.md#the-cost-model-route-choice")
    L.append("")
    L.append('#include "../extensions/potrf_launch_plan.hh"')
    L.append("#include <batchlas/arch/arch_key.hh>")
    L.append("")
    L.append("namespace batchlas::potrf_profile {")
    L.append("")
    L.append("struct Entry {")
    L.append("    bool present = false;                   // false: unfittable, not a candidate")
    L.append("    launch_plan::CostConstants c{};")
    L.append("    launch_plan::SupportRegion box{};       // rows == 0: borrowed, always extrapolated")
    L.append("};")
    L.append("")
    L.append("struct Profile {")
    L.append("    bool model_enabled = false;   // the profile's ship-gate verdict")
    L.append("    double margin = 0;")
    L.append("    int max_threads_per_cu = 0;")
    L.append("    int max_groups_per_cu = 0;")
    L.append("    potrf_plan::KernelRegs regs[4]{};   // float, double, cfloat, cdouble")
    L.append("    Entry e[5][4][2]{};                 // kPotrfOrder x dtype x {Lower, Upper}")
    L.append("};")
    L.append("")
    for name in PROFILES:
        p = profiles[name]
        f = p["device_facts"]
        L.append(f"// {name}: gate {p['gate']['verdict']}; fitted at {p['provenance'].get('fit_git_sha')}.")
        L.append(f"inline constexpr Profile k_{name}{{")
        L.append(f"    {'true' if p['gate']['verdict'] == 'PASS' else 'false'}, {num(p['margin'])}, "
                 f"{f['max_threads_per_cu']}, {f['max_groups_per_cu']},")
        L.append("    {" + ", ".join(regs(f.get("regs", {}).get(d, {})) for d in DTYPES) + "},")
        L.append("    {")
        for r in ROUTES:
            L.append(f"        {{  // {r}")
            for d in DTYPES:
                es = [p["routes"].get(r, {}).get(d, {}).get(u) for u in ("L", "U")]
                L.append(f"            {{{entry(es[0])}, {entry(es[1])}}},  // {d}")
            L.append("        },")
        L.append("    }};")
        L.append("")
    L.append("inline constexpr const Profile* profile_for(arch::RoutingProfile p) {")
    L.append("    switch (p) {")
    for name in PROFILES:
        L.append(f"        case arch::RoutingProfile::{name}: return &k_{name};")
    L.append("        default: return nullptr;")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("}  // namespace batchlas::potrf_profile")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()
    profiles = {}
    for name in PROFILES:
        with open(os.path.join(HERE, "profiles", name + ".json")) as f:
            profiles[name] = json.load(f)
    text = render(profiles)
    if args.check:
        try:
            with open(args.out) as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != text:
            print(f"{args.out} is stale: rerun evaluation/routing/gen_profile_header.py", file=sys.stderr)
            return 1
        print("potrf profile header matches the committed profiles")
        return 0
    with open(args.out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
